#!/usr/bin/env bash
# Build the public ARM32 ONNX/Sherpa dependency closure.
set -euo pipefail

DEPS_ROOT="${1:?usage: build-public-neural-deps.sh <public-deps-root> <armhf-root>}"
ARMHF_ROOT="${2:?usage: build-public-neural-deps.sh <public-deps-root> <armhf-root>}"
OUT="$DEPS_ROOT/neural"
ORT_SOURCE="$DEPS_ROOT/onnxruntime-source"
SHERPA_SOURCE="$DEPS_ROOT/sherpa-onnx-source"
SPEEX_ARCHIVE="$DEPS_ROOT/speexdsp-SpeexDSP-1.2.1.tar.gz"
CROSS="${LIBREECHO_NEURAL_CROSS:-$ARMHF_ROOT/usr/bin/arm-linux-gnueabihf-}"
JOBS="${JOBS:-2}"
ORT_COMMIT=8f0278c77bf44b0cc83c098c6c722b92a36ac4b5
SHERPA_COMMIT=546df6f963ae719dddd8b8d10749e9d9086b0d86
SPEEX_SHA=d17ca363654556a4ff1d02cc13d9eb1fc5a8642c90b40bd54ce266c3807b91a7

fail() { echo "ERROR: $*" >&2; exit 1; }

for tool in cmake make tar sha256sum; do
  command -v "$tool" >/dev/null || fail "required build tool is missing: $tool"
done
for compiler in gcc g++ ar ranlib strip nm; do
  [[ -x "${CROSS}${compiler}" ]] || fail "ARMHF toolchain member is missing: ${CROSS}${compiler}"
done
[[ -d "$ORT_SOURCE/.git" ]] || fail "pinned ONNX Runtime source checkout is missing: $ORT_SOURCE"
[[ -d "$SHERPA_SOURCE/.git" ]] || fail "pinned Sherpa-ONNX source checkout is missing: $SHERPA_SOURCE"
[[ "$(git -C "$ORT_SOURCE" rev-parse HEAD)" == "$ORT_COMMIT" ]] || fail "ONNX Runtime source identity changed"
[[ "$(git -C "$SHERPA_SOURCE" rev-parse HEAD)" == "$SHERPA_COMMIT" ]] || fail "Sherpa-ONNX source identity changed"
[[ -f "$SPEEX_ARCHIVE" && ! -L "$SPEEX_ARCHIVE" ]] || fail "SpeexDSP source archive is missing"
[[ "$(sha256sum "$SPEEX_ARCHIVE" | awk '{print $1}')" == "$SPEEX_SHA" ]] || fail "SpeexDSP source identity changed"

rm -rf -- "$OUT"
mkdir -p "$OUT" "$OUT/onnxruntime-build" "$OUT/onnxruntime-prefix/lib" "$OUT/sherpa-onnx-prefix"
WORK="${RUNNER_TEMP:?set RUNNER_TEMP}/libreecho-neural-build"
rm -rf -- "$WORK"
mkdir -p "$WORK"

# Build full static ONNX Runtime once. The mature UI Makefile consumes both the
# component archives and the dependency archives generated by this build.
ORT_WORK="$WORK/onnxruntime"
ORT_BUILD="$ORT_WORK/build"
mkdir -p "$ORT_WORK"
cmake -S "$ORT_SOURCE/cmake" -B "$ORT_BUILD" \
  -DCMAKE_BUILD_TYPE=MinSizeRel \
  -DCMAKE_SYSTEM_NAME=Linux \
  -DCMAKE_SYSTEM_PROCESSOR=arm \
  -DCMAKE_SYSROOT="$ARMHF_ROOT" \
  -DCMAKE_C_COMPILER="${CROSS}gcc" \
  -DCMAKE_CXX_COMPILER="${CROSS}g++" \
  -DCMAKE_AR="${CROSS}ar" \
  -DCMAKE_RANLIB="${CROSS}ranlib" \
  -DCMAKE_STRIP="${CROSS}strip" \
  -DCMAKE_C_FLAGS="-march=armv7-a -mfpu=neon-vfpv4 -mfloat-abi=hard -ffunction-sections -fdata-sections -ffile-prefix-map=$ORT_WORK=ort-build -ffile-prefix-map=$ORT_SOURCE=ort-src" \
  -DCMAKE_CXX_FLAGS="-march=armv7-a -mfpu=neon-vfpv4 -mfloat-abi=hard -ffunction-sections -fdata-sections -ffile-prefix-map=$ORT_WORK=ort-build -ffile-prefix-map=$ORT_SOURCE=ort-src" \
  -DCMAKE_ARCHIVE_OUTPUT_DIRECTORY="$ORT_BUILD" \
  -Donnxruntime_CROSS_COMPILING=ON \
  -Donnxruntime_BUILD_SHARED_LIB=OFF \
  -Donnxruntime_BUILD_UNIT_TESTS=OFF \
  -Donnxruntime_BUILD_BENCHMARKS=OFF \
  -Donnxruntime_ENABLE_PYTHON=OFF \
  -Donnxruntime_ENABLE_TRAINING=OFF \
  -Donnxruntime_ENABLE_NVTX=OFF \
  -Donnxruntime_USE_CUDA=OFF \
  -Donnxruntime_USE_TENSORRT=OFF \
  -Donnxruntime_DISABLE_CONTRIB_OPS=ON \
  -Donnxruntime_DISABLE_ML_OPS=ON \
  -Donnxruntime_DISABLE_GENERATION_OPS=ON \
  -Donnxruntime_DISABLE_OPTIONAL_TYPE=ON \
  -Donnxruntime_DISABLE_SPARSE_TENSORS=ON \
  -Donnxruntime_DISABLE_RTTI=ON \
  -Donnxruntime_REDUCED_OPS_BUILD=OFF \
  -Donnxruntime_USE_FULL_PROTOBUF=OFF
cmake --build "$ORT_BUILD" --parallel "$JOBS"

copy_named_archive() {
  local name="$1" destination="$2" source
  source="$(find "$ORT_BUILD" -type f -name "$name" -print -quit)"
  [[ -n "$source" ]] || fail "ONNX Runtime archive is missing: $name"
  mkdir -p "$destination"
  install -m 0644 "$source" "$destination/$name"
}

ORT_STAGE="$OUT/onnxruntime-build"
for archive in \
    libonnxruntime_session.a libonnxruntime_optimizer.a \
    libonnxruntime_providers.a libonnxruntime_graph.a libonnxruntime_framework.a \
    libonnxruntime_common.a libonnxruntime_mlas.a libonnxruntime_util.a \
    libonnxruntime_flatbuffers.a libonnxruntime_lora.a; do
  copy_named_archive "$archive" "$ORT_STAGE"
done
copy_named_archive libonnx.a "$ORT_STAGE/_deps/onnx-build"
copy_named_archive libonnx_proto.a "$ORT_STAGE/_deps/onnx-build"
copy_named_archive libprotobuf-lite.a "$ORT_STAGE/_deps/protobuf-build"
copy_named_archive libflatbuffers.a "$ORT_STAGE/_deps/flatbuffers-build"
absl_count=0
while IFS= read -r -d '' source; do
  mkdir -p "$ORT_STAGE/_deps/abseil_cpp-build"
  install -m 0644 "$source" "$ORT_STAGE/_deps/abseil_cpp-build/$(basename -- "$source")"
  absl_count=$((absl_count + 1))
done < <(find "$ORT_BUILD" -maxdepth 1 -type f -name 'libabsl_*.a' -print0 | LC_ALL=C sort -z)
((absl_count > 0)) || fail "ONNX Runtime Abseil dependency closure is missing"

# ORT v1.27 emits component archives by default. Build its RE2 target, then
# assemble a conventional monolithic archive for Sherpa's pre-installed ORT
# probe. The mature UI link still consumes the component closure above.
cmake --build "$ORT_BUILD" --target re2 --parallel "$JOBS"
re2="$(find "$ORT_BUILD" -type f -name libre2.a -print -quit)"
[[ -n "$re2" ]] || fail "ONNX Runtime RE2 archive is missing"
install -m 0644 "$re2" "$OUT/onnxruntime-prefix/lib/libre2.a"

# Sherpa includes the ONNX Runtime headers flat (onnxruntime_cxx_api.h), so
# stage an install-style flat include directory next to the static library.
# The source-tree layout (include/onnxruntime/core/session/) does not satisfy
# that include contract.
ort_headers="$ORT_SOURCE/include/onnxruntime/core/session"
[[ -f "$ort_headers/onnxruntime_c_api.h" && -f "$ort_headers/onnxruntime_cxx_api.h" ]] || \
  fail "ONNX Runtime public headers are missing from the pinned source checkout"
mkdir -p "$OUT/onnxruntime-prefix/include"
for header in "$ort_headers"/*; do
  [[ -f "$header" ]] || continue
  install -m 0644 "$header" "$OUT/onnxruntime-prefix/include/$(basename -- "$header")"
done
[[ -f "$OUT/onnxruntime-prefix/include/onnxruntime_cxx_api.h" ]] || \
  fail "flat ONNX Runtime include staging failed"
{
  printf 'CREATE %s\n' "$OUT/onnxruntime-prefix/lib/libonnxruntime.a"
  for archive in \
      libonnxruntime_session.a libonnxruntime_optimizer.a \
      libonnxruntime_providers.a libonnxruntime_graph.a \
      libonnxruntime_framework.a libonnxruntime_common.a \
      libonnxruntime_mlas.a libonnxruntime_util.a \
      libonnxruntime_flatbuffers.a libonnxruntime_lora.a; do
    printf 'ADDLIB %s\n' "$ORT_STAGE/$archive"
  done
  printf 'SAVE\nEND\n'
} | ar -M

# The ORT configure step populated the exact Python generator used by the
# reduced wakeword build. Copy only that source tree into the artifact.
flatbuffers_python="$(find "$ORT_BUILD" -type f -path '*/_deps/flatbuffers-src/python/flatbuffers/__init__.py' -print -quit)"
[[ -n "$flatbuffers_python" ]] || fail "ONNX Runtime FlatBuffers Python source is missing"
flatbuffers_root="${flatbuffers_python%/flatbuffers/__init__.py}"
cp -a -- "$flatbuffers_root" "$OUT/flatbuffers-python"

# Build the static Sherpa-ONNX libraries used by the STT/TTS adapters. All
# optional binaries, tests, websocket support, GPU paths, and speaker
# diarization are disabled; the C and C++ APIs and Piper TTS remain enabled.
SHERPA_BUILD="$WORK/sherpa"
SHERPA_PREFIX="$OUT/sherpa-onnx-prefix"
SHERPA_ONNXRUNTIME_INCLUDE_DIR="$OUT/onnxruntime-prefix/include" \
SHERPA_ONNXRUNTIME_LIB_DIR="$OUT/onnxruntime-prefix/lib" \
cmake -S "$SHERPA_SOURCE" -B "$SHERPA_BUILD" \
  -DCMAKE_BUILD_TYPE=MinSizeRel \
  -DCMAKE_INSTALL_PREFIX="$SHERPA_PREFIX" \
  -DCMAKE_SYSTEM_NAME=Linux \
  -DCMAKE_SYSTEM_PROCESSOR=arm \
  -DCMAKE_SYSROOT="$ARMHF_ROOT" \
  -DCMAKE_C_COMPILER="${CROSS}gcc" \
  -DCMAKE_CXX_COMPILER="${CROSS}g++" \
  -DCMAKE_AR="${CROSS}ar" \
  -DCMAKE_RANLIB="${CROSS}ranlib" \
  -DCMAKE_STRIP="${CROSS}strip" \
  -DCMAKE_C_FLAGS="-march=armv7-a -mfpu=neon-vfpv4 -mfloat-abi=hard -ffunction-sections -fdata-sections" \
  -DCMAKE_CXX_FLAGS="-march=armv7-a -mfpu=neon-vfpv4 -mfloat-abi=hard -ffunction-sections -fdata-sections" \
  -DBUILD_SHARED_LIBS=OFF \
  -DSHERPA_ONNX_ENABLE_PYTHON=OFF \
  -DSHERPA_ONNX_ENABLE_TESTS=OFF \
  -DSHERPA_ONNX_ENABLE_PORTAUDIO=OFF \
  -DSHERPA_ONNX_ENABLE_BINARY=OFF \
  -DSHERPA_ONNX_ENABLE_C_API=ON \
  -DSHERPA_ONNX_ENABLE_WEBSOCKET=OFF \
  -DSHERPA_ONNX_ENABLE_TTS=ON \
  -DSHERPA_ONNX_ENABLE_SPEAKER_DIARIZATION=OFF \
  -DSHERPA_ONNX_USE_PRE_INSTALLED_ONNXRUNTIME_IF_AVAILABLE=ON \
  -DSHERPA_ONNX_LINK_LIBSTDCPP_STATICALLY=ON
SHERPA_ONNXRUNTIME_INCLUDE_DIR="$OUT/onnxruntime-prefix/include" \
SHERPA_ONNXRUNTIME_LIB_DIR="$OUT/onnxruntime-prefix/lib" \
cmake --build "$SHERPA_BUILD" --parallel "$JOBS"
SHERPA_ONNXRUNTIME_INCLUDE_DIR="$OUT/onnxruntime-prefix/include" \
SHERPA_ONNXRUNTIME_LIB_DIR="$OUT/onnxruntime-prefix/lib" \
cmake --install "$SHERPA_BUILD"

# Build the ARM32 SpeexDSP prefix used by the wakeword relink and UI adapters.
SPEEX_WORK="$WORK/speex"
mkdir -p "$SPEEX_WORK"
tar -xf "$SPEEX_ARCHIVE" -C "$SPEEX_WORK"
speex_source="$(find "$SPEEX_WORK" -mindepth 1 -maxdepth 1 -type d -print -quit)"
[[ -n "$speex_source" ]] || fail "SpeexDSP source directory is missing"
(
  cd "$speex_source"
  ./autogen.sh
  # The staged cross compiler is not on PATH; pass it explicitly. --sysroot
  # rides in CFLAGS so the configure link probe and every compile/link step
  # resolve the staged ARMHF root (configure does not inherit CMake's
  # -DCMAKE_SYSROOT).
  CC="${CROSS}gcc" \
    CFLAGS="-Os -march=armv7-a -mfpu=neon-vfpv4 -mfloat-abi=hard --sysroot=$ARMHF_ROOT" \
    ./configure --host=arm-linux-gnueabihf --prefix="$OUT/speexdsp-prefix" \
      --disable-shared --enable-static --enable-fixed-point --disable-examples
  make -j"$JOBS"
  make install
)
sed -i -e 's|^prefix=.*|prefix=/opt/libreecho/speexdsp|' \
  "$OUT/speexdsp-prefix/lib/pkgconfig/speexdsp.pc"
sed -i -e "s|^libdir=.*|libdir='/opt/libreecho/speexdsp/lib'|" \
  "$OUT/speexdsp-prefix/lib/libspeexdsp.la"

for required in \
    "$OUT/onnxruntime-prefix/include/onnxruntime_cxx_api.h" \
    "$OUT/onnxruntime-build/libonnxruntime_session.a" \
    "$OUT/onnxruntime-build/_deps/onnx-build/libonnx.a" \
    "$OUT/onnxruntime-prefix/lib/libonnxruntime.a" \
    "$OUT/onnxruntime-prefix/lib/libre2.a" \
    "$OUT/sherpa-onnx-prefix/lib/libsherpa-onnx-core.a" \
    "$OUT/flatbuffers-python/flatbuffers/__init__.py" \
    "$OUT/speexdsp-prefix/lib/libspeexdsp.a"; do
  [[ -f "$required" ]] || fail "neural dependency output is incomplete: $required"
done

cat > "$OUT/NEURAL_DEPENDENCY_MANIFEST" <<EOF
schema=libreecho-public-neural-deps-v1
onnxruntime_commit=$ORT_COMMIT
sherpa_onnx_commit=$SHERPA_COMMIT
speexdsp_sha256=$SPEEX_SHA
cross_prefix=$CROSS
jobs=$JOBS
EOF
printf 'public_neural_dependencies=PASS\n'
sha256sum "$OUT/NEURAL_DEPENDENCY_MANIFEST"
